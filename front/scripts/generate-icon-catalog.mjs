function isNoise(name) {
  if (/^\d/.test(name)) return true;
  if (/_(mp|k|k_plus)$/.test(name)) return true;
  if (/^\d+k(_plus)?$/.test(name)) return true;
  if (/^\d+mp$/.test(name)) return true;
  if (/fps/.test(name) && /select|30|60|24/.test(name)) return true;
  return false;
}

function labelsFor(name) {
  const parts = name.split('_').filter(Boolean);
  const translated = parts.map((p) => WORD_FR[p] ?? p.replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase());
  const phrase = translated.join(' ').trim();
  const raw = parts.join(' ');
  const labels = new Set();
  if (phrase) labels.add(phrase);
  if (raw && raw !== phrase) labels.add(raw);
  for (const t of translated) {
    if (t.length > 2) labels.add(t);
  }
  // keep first FR-ish label preferred
  return [...labels].slice(0, 8);
}

